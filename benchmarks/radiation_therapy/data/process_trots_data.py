#!/usr/bin/env python3
"""
Process TROTS Dataset for Scenario Approach Tool

This script converts TROTS (Radiotherapy Optimisation Test Set) MATLAB data
into the format required by the Scenario Approach Tool.

TROTS Dataset Reference:
- Breedveld et al., "The TROTS dataset: Open radiotherapy optimization data"
- Available from Zenodo: https://doi.org/10.5281/zenodo.2540tried to

Data Format:
- Dose-influence matrices D[v,b]: dose to voxel v from unit intensity of beamlet b
- Multiple anatomical structures (target, OARs)
- Pre-computed reference solutions

Output:
- CSV files suitable for solve_qp() function
- Scenarios generated by perturbing dose matrices (simulating setup uncertainty)
"""

import mat73
import numpy as np
import pandas as pd
from pathlib import Path
from scipy import sparse
import warnings

def load_trots_patient(filepath):
    """
    Load a TROTS patient MATLAB file.

    Returns:
        dict: Parsed data with structure information
    """
    data = mat73.loadmat(str(filepath))

    # Extract key components
    result = {
        'matrices': {},
        'n_beamlets': None,
        'structures': [],
        'solution': data.get('solutionX', None),
    }

    # Parse dose matrices
    matrix_data = data['data']['matrix']

    for m in matrix_data:
        if isinstance(m, dict):
            name = m.get('Name', 'Unknown')
            A = m.get('A', None)

            if A is not None and isinstance(A, np.ndarray):
                if len(A.shape) == 2:
                    result['matrices'][name] = {
                        'D': A,  # Dose-influence matrix
                        'n_voxels': A.shape[0],
                        'n_beamlets': A.shape[1]
                    }
                    if result['n_beamlets'] is None:
                        result['n_beamlets'] = A.shape[1]
                    result['structures'].append({
                        'name': name,
                        'n_voxels': A.shape[0],
                        'type': 'voxel'
                    })
                elif len(A.shape) == 1:
                    # Mean dose vector (aggregated over structure)
                    result['matrices'][name] = {
                        'D': A.reshape(1, -1),  # Convert to row vector
                        'n_voxels': 1,
                        'n_beamlets': len(A),
                        'is_mean': True
                    }
                    result['structures'].append({
                        'name': name,
                        'n_voxels': 1,
                        'type': 'mean'
                    })

    return result


def sample_voxels(D, n_target, seed=42):
    """
    Sample voxels from a large dose matrix while preserving boundary voxels.

    Prioritizes voxels with high dose variance (more sensitive to optimization).

    Args:
        D: Dose matrix (n_voxels, n_beamlets)
        n_target: Target number of voxels
        seed: Random seed

    Returns:
        Sampled dose matrix and indices
    """
    if D.shape[0] <= n_target:
        return D, np.arange(D.shape[0])

    np.random.seed(seed)

    # Compute variance across beamlets for each voxel (high variance = boundary)
    variance = np.var(D, axis=1)

    # Take top 50% by variance (boundary/important voxels)
    n_important = min(n_target // 2, D.shape[0] // 4)
    important_idx = np.argsort(variance)[-n_important:]

    # Random sample the rest
    remaining_idx = np.setdiff1d(np.arange(D.shape[0]), important_idx)
    n_random = min(n_target - n_important, len(remaining_idx))
    random_idx = np.random.choice(remaining_idx, n_random, replace=False)

    # Combine
    selected_idx = np.sort(np.concatenate([important_idx, random_idx]))

    return D[selected_idx], selected_idx


def sample_beamlets(D, n_target, seed=42):
    """
    Sample beamlets from a large dose matrix.

    Prioritizes beamlets with high total dose contribution.

    Args:
        D: Dose matrix (n_voxels, n_beamlets)
        n_target: Target number of beamlets
        seed: Random seed

    Returns:
        Sampled dose matrix and indices
    """
    if D.shape[1] <= n_target:
        return D, np.arange(D.shape[1])

    np.random.seed(seed)

    # Compute total dose contribution for each beamlet
    total_dose = np.sum(D, axis=0)

    # Take top 70% by dose contribution (important beamlets)
    n_important = int(0.7 * n_target)
    important_idx = np.argsort(total_dose)[-n_important:]

    # Random sample the rest for diversity
    remaining_idx = np.setdiff1d(np.arange(D.shape[1]), important_idx)
    n_random = n_target - n_important
    random_idx = np.random.choice(remaining_idx, n_random, replace=False)

    # Combine
    selected_idx = np.sort(np.concatenate([important_idx, random_idx]))

    return D[:, selected_idx], selected_idx


def generate_scenarios(D_nominal, n_scenarios=200, shift_range=5.0, seed=42):
    """
    Generate scenarios by perturbing the nominal dose matrix.

    Simulates setup uncertainty by:
    1. Applying voxel-wise perturbations (dose scaling)
    2. Adding random noise to dose coefficients

    This models:
    - Patient positioning errors (±5mm typical)
    - Organ motion between fractions
    - Systematic vs random errors

    Args:
        D_nominal: Nominal dose matrix (n_voxels, n_beamlets)
        n_scenarios: Number of scenarios to generate
        shift_range: Maximum shift in mm
        seed: Random seed

    Returns:
        deltas: (n_scenarios, 3) array of shift parameters
        D_scenarios: list of perturbed dose matrices
    """
    np.random.seed(seed)
    n_voxels, n_beamlets = D_nominal.shape

    # Generate shift parameters (delta_x, delta_y, delta_z) in mm
    # Mix of grid and random scenarios

    # Grid scenarios (systematic errors)
    shifts = [-shift_range, -shift_range/2, 0, shift_range/2, shift_range]
    grid_scenarios = []
    for dx in shifts:
        for dy in shifts:
            for dz in shifts:
                grid_scenarios.append([dx, dy, dz])
    grid_scenarios = np.array(grid_scenarios)

    # Random scenarios (random errors)
    n_grid = len(grid_scenarios)
    n_random = max(0, n_scenarios - n_grid)

    if n_random > 0:
        random_scenarios = np.random.uniform(-shift_range, shift_range, (n_random, 3))
        deltas = np.vstack([grid_scenarios, random_scenarios])
    else:
        deltas = grid_scenarios[:n_scenarios]

    # Truncate to requested number
    deltas = deltas[:n_scenarios]

    # Generate perturbed dose matrices
    D_scenarios = []

    for i, delta in enumerate(deltas):
        # Perturbation model:
        # D_perturbed[v,b] = D_nominal[v,b] * (1 + noise_v + shift_effect)
        #
        # shift_effect models how voxel position affects dose:
        # - Anterior-posterior (y) shift has biggest impact on OAR dose
        # - Deeper voxels have more attenuation

        # Compute perturbation factor
        shift_magnitude = np.linalg.norm(delta)

        # Voxel-dependent perturbation (different voxels respond differently to shift)
        voxel_sensitivity = 0.02 * (1 + np.random.randn(n_voxels) * 0.5)  # 2% ± 1% per mm
        voxel_factor = 1 + voxel_sensitivity * (delta[1] / shift_range)  # Y (AP) most important

        # Beamlet-dependent perturbation (beam angle affects sensitivity)
        beamlet_sensitivity = 0.01 * (1 + np.random.randn(n_beamlets) * 0.3)
        beamlet_factor = 1 + beamlet_sensitivity * (delta[0] / shift_range)  # X affects beam entry

        # Random noise
        noise = 1 + 0.02 * np.random.randn(n_voxels, n_beamlets)  # 2% random noise

        # Apply perturbations
        D_perturbed = D_nominal * voxel_factor[:, np.newaxis] * beamlet_factor[np.newaxis, :] * noise

        # Ensure non-negative doses
        D_perturbed = np.maximum(D_perturbed, 0)

        D_scenarios.append(D_perturbed)

    return deltas, D_scenarios


def create_qp_problem(D_target, D_oars, target_dose=70.0, oar_limits=None,
                      weights=None, max_intensity=100.0):
    """
    Create QP matrices for radiation therapy optimization.

    Problem:
        minimize    (1/2) x' Q x + c' x
        subject to  D_oar[v,:] x <= D_max_oar[v]  (OAR dose limits)
                    D_target[v,:] x >= D_min_target (target coverage)
                    0 <= x <= max_intensity        (physical limits)

    Args:
        D_target: Dose matrix for target (n_target, n_beamlets)
        D_oars: dict of {name: D_matrix} for OARs
        target_dose: Prescription dose in Gy
        oar_limits: dict of {name: max_dose} for OARs
        weights: dict of {name: weight} for objective function
        max_intensity: Maximum beamlet intensity

    Returns:
        Q, c, G, h, A_target, b_target: QP matrices
    """
    n_beamlets = D_target.shape[1]
    n_target = D_target.shape[0]

    # Default weights
    if weights is None:
        weights = {'target': 10.0, 'oar': 1.0, 'normal': 0.1}

    # Objective: minimize weighted sum of dose deviations
    # For target: (D*x - target_dose)^2 with high weight
    # For OARs: (D*x)^2 with lower weight (penalize all dose)

    # Q = 2 * sum_s w_s * D_s' * D_s
    # c = -2 * sum_s w_s * D_s' * target_s

    w_target = weights.get('target', 10.0)
    w_oar = weights.get('oar', 1.0)

    # Target contribution
    Q = w_target * D_target.T @ D_target
    c = -w_target * D_target.T @ (target_dose * np.ones(n_target))

    # OAR contribution (penalize dose, no target)
    for name, D_oar in D_oars.items():
        w = weights.get(name, w_oar)
        Q += w * D_oar.T @ D_oar
        # c += 0 for OARs (target is zero dose)

    # Ensure Q is symmetric and PSD
    Q = (Q + Q.T) / 2

    # Normalize Q to improve conditioning
    # Scale so that max diagonal element is ~1
    scale_factor = np.max(np.diag(Q))
    if scale_factor > 1:
        Q = Q / scale_factor
        c = c / scale_factor

    # Add regularization for numerical stability
    Q += 1e-4 * np.eye(n_beamlets)

    # Hard constraints: 0 <= x <= max_intensity
    # In form G @ x + h <= 0:
    # -x <= 0  (lower bound)
    # x - max_intensity <= 0  (upper bound)

    G_lower = -np.eye(n_beamlets)
    h_lower = np.zeros(n_beamlets)

    G_upper = np.eye(n_beamlets)
    h_upper = -max_intensity * np.ones(n_beamlets)

    G = np.vstack([G_lower, G_upper])
    h = np.concatenate([h_lower, h_upper])

    # Target coverage constraints: D_target @ x >= D_min
    # In form A @ x + b <= 0:  -D_target @ x + D_min <= 0
    D_min = 0.95 * target_dose  # 95% of prescription (D95 coverage)
    A_target = -D_target
    b_target = D_min * np.ones(n_target)

    return Q, c.reshape(-1, 1), G, h.reshape(-1, 1), A_target, b_target


def build_affine_constraint_strings(D_nominal, deltas, D_scenarios, b_values):
    """
    Build affine constraint expressions as strings for A_d(delta).

    For each constraint coefficient a_ij, compute:
    a_ij(delta) = a_ij_0 + grad_x * delta[0] + grad_y * delta[1] + grad_z * delta[2]

    Args:
        D_nominal: Nominal dose matrix
        deltas: Scenario shift parameters
        D_scenarios: Perturbed dose matrices
        b_values: Right-hand side values

    Returns:
        A_d_strings: Matrix of string expressions
        b_d_strings: Vector of string expressions
    """
    n_voxels, n_beamlets = D_nominal.shape
    n_scenarios = len(deltas)

    # Estimate gradients from scenarios using least squares
    # For each coefficient, fit: a = a_0 + grad . delta

    A_d_strings = []

    for i in range(n_voxels):
        row_strings = []
        for j in range(n_beamlets):
            # Collect values across scenarios
            values = np.array([D_scenarios[k][i, j] for k in range(n_scenarios)])

            # Fit linear model: value = a0 + a1*dx + a2*dy + a3*dz
            # Design matrix: [1, dx, dy, dz]
            X = np.column_stack([np.ones(n_scenarios), deltas])

            # Solve least squares
            coeffs, _, _, _ = np.linalg.lstsq(X, values, rcond=None)

            a0, grad_x, grad_y, grad_z = coeffs

            # Build string expression
            # Use proper format: a0 + grad_x*delta[0] + grad_y*delta[1] + grad_z*delta[2]
            expr = f"{a0:.6f}"
            if abs(grad_x) > 1e-10:
                if grad_x >= 0:
                    expr += f"+{grad_x:.6f}*delta[0]"
                else:
                    expr += f"{grad_x:.6f}*delta[0]"
            if abs(grad_y) > 1e-10:
                if grad_y >= 0:
                    expr += f"+{grad_y:.6f}*delta[1]"
                else:
                    expr += f"{grad_y:.6f}*delta[1]"
            if abs(grad_z) > 1e-10:
                if grad_z >= 0:
                    expr += f"+{grad_z:.6f}*delta[2]"
                else:
                    expr += f"{grad_z:.6f}*delta[2]"

            row_strings.append(expr)

        A_d_strings.append(row_strings)

    # b_d is constant (doesn't depend on delta)
    b_d_strings = [f"{b:.6f}" for b in b_values]

    return A_d_strings, b_d_strings


def process_prostate_bt(data_dir, output_dir, patient_id=1,
                        n_voxels_target=100, n_beamlets=50, n_scenarios=200):
    """
    Process Prostate Brachytherapy data for scenario approach.

    Args:
        data_dir: Directory containing TROTS .mat files
        output_dir: Output directory for benchmark files
        patient_id: Which patient to use (1-25)
        n_voxels_target: Target number of voxels per structure
        n_beamlets: Target number of beamlets (decision variables)
        n_scenarios: Number of scenarios to generate
    """
    data_dir = Path(data_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Load patient data
    filepath = data_dir / f"Prostate_BT_{patient_id:02d}.mat"
    print(f"Loading {filepath}...")
    patient = load_trots_patient(filepath)

    print(f"Original data: {patient['n_beamlets']} beamlets")
    print(f"Structures: {[s['name'] for s in patient['structures']]}")

    # Select key structures
    structures = {
        'Prostate': None,     # Target
        'Rectum': None,       # OAR
        'Bladder': None,      # OAR
        'Urethra': None,      # OAR (within target)
    }

    for name in structures:
        if name in patient['matrices']:
            structures[name] = patient['matrices'][name]['D']
            print(f"  {name}: {structures[name].shape}")
        else:
            # Try partial match
            for key in patient['matrices']:
                if name.lower() in key.lower() and patient['matrices'][key]['D'].shape[0] > 1:
                    structures[name] = patient['matrices'][key]['D']
                    print(f"  {name} (from {key}): {structures[name].shape}")
                    break

    # Get prostate (target)
    D_target_full = structures['Prostate']
    if D_target_full is None:
        raise ValueError("Prostate structure not found!")

    # Sample beamlets first (applied to all structures)
    beamlet_idx = None
    if D_target_full.shape[1] > n_beamlets:
        _, beamlet_idx = sample_beamlets(D_target_full, n_beamlets, seed=42)
        print(f"\nSampled {len(beamlet_idx)} beamlets from {D_target_full.shape[1]}")

    # Sample voxels and apply beamlet sampling
    D_target, target_idx = sample_voxels(D_target_full, n_voxels_target, seed=42)
    if beamlet_idx is not None:
        D_target = D_target[:, beamlet_idx]
    print(f"Target (Prostate): {D_target.shape}")

    D_oars = {}
    for name in ['Rectum', 'Bladder', 'Urethra']:
        if structures[name] is not None:
            D_oar, _ = sample_voxels(structures[name], n_voxels_target // 2, seed=43 + len(D_oars))
            if beamlet_idx is not None:
                D_oar = D_oar[:, beamlet_idx]
            D_oars[name] = D_oar
            print(f"OAR ({name}): {D_oar.shape}")

    # Treatment parameters (brachytherapy typically uses 145 Gy prescription)
    target_dose = 145.0  # Gy (brachytherapy uses high dose per fraction)
    oar_limits = {
        'Rectum': 100.0,   # Lower than target due to proximity
        'Bladder': 120.0,
        'Urethra': 160.0,  # Can tolerate slightly higher (within target)
    }

    # Generate scenarios
    print(f"\nGenerating {n_scenarios} scenarios...")

    # Combined dose matrix for scenario generation
    D_all = np.vstack([D_target] + list(D_oars.values()))

    deltas, D_scenarios_all = generate_scenarios(D_all, n_scenarios, shift_range=5.0, seed=42)

    # Split scenarios back into structures
    n_t = D_target.shape[0]
    cumsum = np.cumsum([n_t] + [d.shape[0] for d in D_oars.values()])

    # Build constraint matrices
    # Soft constraints (with scenarios):
    #   OAR upper bounds: D_oar @ x <= D_max
    #   Target lower bounds: -D_target @ x <= -D_min (inverted)

    D_min = 0.95 * target_dose

    # Build A_d matrix (soft constraints affected by uncertainty)
    A_rows = []
    b_values = []

    # Target coverage (minimum dose): -D @ x + D_min <= 0 means D @ x >= D_min
    A_rows.extend(-D_target)
    b_values.extend([D_min] * D_target.shape[0])  # Positive b for target min

    # OAR limits (maximum dose): D @ x - D_max <= 0 means D @ x <= D_max
    for name, D_oar in D_oars.items():
        A_rows.extend(D_oar)
        b_values.extend([-oar_limits.get(name, 100.0)] * D_oar.shape[0])  # Negative b for OAR max

    A_nominal = np.array(A_rows)
    b_nominal = np.array(b_values)

    # Generate scenario-perturbed A matrices
    A_scenarios = []
    for k in range(n_scenarios):
        D_k = D_scenarios_all[k]

        # Split by structure
        D_target_k = D_k[:n_t]

        A_k_rows = list(-D_target_k)  # Target min dose

        idx = n_t
        for name, D_oar in D_oars.items():
            n_oar = D_oar.shape[0]
            D_oar_k = D_k[idx:idx+n_oar]
            A_k_rows.extend(D_oar_k)  # OAR max dose
            idx += n_oar

        A_scenarios.append(np.array(A_k_rows))

    # Build affine constraint strings
    print("Building affine constraint expressions...")
    A_d_strings, b_d_strings = build_affine_constraint_strings(
        A_nominal, deltas, A_scenarios, b_nominal  # b already has correct signs
    )

    # Create QP objective
    print("Building QP objective...")
    Q, c, G, h, _, _ = create_qp_problem(
        D_target, D_oars, target_dose=target_dose,
        oar_limits=oar_limits,
        weights={'target': 10.0, 'Rectum': 2.0, 'Bladder': 1.5, 'Urethra': 1.0},
        max_intensity=100.0
    )

    # Save files
    print(f"\nSaving to {output_dir}...")

    # Scenarios (no header for compatibility with load_file)
    pd.DataFrame(deltas).to_csv(output_dir / 'scenarios.csv', index=False, header=False)

    # A_d matrix (affine expressions)
    pd.DataFrame(A_d_strings).to_csv(output_dir / 'A_d.csv', index=False, header=False)

    # b_d vector
    pd.DataFrame(b_d_strings).to_csv(output_dir / 'b_d.csv', index=False, header=False)

    # Q matrix
    pd.DataFrame(Q).to_csv(output_dir / 'Q.csv', index=False, header=False)

    # c vector
    pd.DataFrame(c).to_csv(output_dir / 'c.csv', index=False, header=False)

    # Hard constraints G, h
    pd.DataFrame(G).to_csv(output_dir / 'G.csv', index=False, header=False)
    pd.DataFrame(h).to_csv(output_dir / 'h.csv', index=False, header=False)

    # Nominal dose matrix (for visualization)
    D_combined = np.vstack([D_target] + list(D_oars.values()))
    pd.DataFrame(D_combined).to_csv(output_dir / 'D_nominal.csv', index=False, header=False)

    # Anatomy info
    with open(output_dir / 'anatomy.txt', 'w') as f:
        f.write(f"Prostate: 0-{D_target.shape[0]-1} (target, {D_target.shape[0]} voxels)\n")
        idx = D_target.shape[0]
        for name, D_oar in D_oars.items():
            f.write(f"{name}: {idx}-{idx + D_oar.shape[0]-1} (OAR, {D_oar.shape[0]} voxels)\n")
            idx += D_oar.shape[0]

    # Parameters
    with open(output_dir / 'parameters.txt', 'w') as f:
        f.write(f"n_beamlets: {D_target.shape[1]}\n")
        f.write(f"n_voxels: {D_combined.shape[0]}\n")
        f.write(f"n_scenarios: {n_scenarios}\n")
        f.write(f"target_dose: {target_dose}\n")
        f.write(f"D_min: {D_min}\n")
        for name, limit in oar_limits.items():
            f.write(f"{name}_max: {limit}\n")
        f.write(f"max_intensity: 100.0\n")

    print("Done!")
    return output_dir


def process_liver(data_dir, output_dir, patient_id=1,
                  n_voxels_target=80, n_beamlets=100, n_scenarios=200):
    """
    Process Liver SBRT data for scenario approach.

    Args:
        data_dir: Directory containing TROTS .mat files
        output_dir: Output directory for benchmark files
        patient_id: Which patient to use (1-10)
        n_voxels_target: Target number of voxels per structure
        n_beamlets: Target number of beamlets
        n_scenarios: Number of scenarios
    """
    data_dir = Path(data_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Load patient data
    filepath = data_dir / f"Liver_{patient_id:02d}.mat"
    print(f"Loading {filepath}...")
    patient = load_trots_patient(filepath)

    print(f"Original data: {patient['n_beamlets']} beamlets")
    print(f"Structures available:")
    for name in patient['matrices']:
        D = patient['matrices'][name]['D']
        if len(D.shape) == 2:
            print(f"  {name}: {D.shape}")

    # Select key structures for liver SBRT
    D_target_full = None
    D_oars_full = {}

    for name, info in patient['matrices'].items():
        D = info['D']
        if len(D.shape) != 2:
            continue

        name_lower = name.lower()

        # Target (PTV)
        if 'ptv' in name_lower and D_target_full is None:
            D_target_full = D
            print(f"Target: {name} {D.shape}")

        # OARs
        elif 'liver' in name_lower and 'minus' not in name_lower:
            D_oars_full['Liver'] = D
        elif 'kidney' in name_lower and '(r)' in name_lower:
            D_oars_full['Kidney_R'] = D
        elif 'kidney' in name_lower and '(l)' in name_lower:
            D_oars_full['Kidney_L'] = D
        elif 'spinal' in name_lower:
            D_oars_full['Spinal_Cord'] = D
        elif 'stomach' in name_lower and 'mean' not in name_lower:
            D_oars_full['Stomach'] = D

    if D_target_full is None:
        raise ValueError("PTV not found!")

    # Sample beamlets
    beamlet_idx = None
    if D_target_full.shape[1] > n_beamlets:
        _, beamlet_idx = sample_beamlets(D_target_full, n_beamlets, seed=42)
        print(f"\nSampled {len(beamlet_idx)} beamlets from {D_target_full.shape[1]}")

    # Sample voxels
    D_target, _ = sample_voxels(D_target_full, n_voxels_target, seed=42)
    if beamlet_idx is not None:
        D_target = D_target[:, beamlet_idx]
    print(f"Target (PTV): {D_target.shape}")

    D_oars = {}
    for name, D_full in D_oars_full.items():
        D_oar, _ = sample_voxels(D_full, n_voxels_target // 3, seed=43 + len(D_oars))
        if beamlet_idx is not None:
            D_oar = D_oar[:, beamlet_idx]
        D_oars[name] = D_oar
        print(f"OAR ({name}): {D_oar.shape}")

    # Treatment parameters (SBRT uses high dose per fraction)
    target_dose = 50.0  # Gy (typical SBRT: 10 Gy x 5 fractions)
    oar_limits = {
        'Liver': 30.0,       # Mean liver dose limit
        'Kidney_R': 18.0,    # Kidney tolerance
        'Kidney_L': 18.0,
        'Spinal_Cord': 25.0, # Spinal cord max
        'Stomach': 35.0,     # GI tolerance
    }

    # Generate scenarios (liver has more motion than prostate)
    print(f"\nGenerating {n_scenarios} scenarios...")
    D_all = np.vstack([D_target] + list(D_oars.values()))
    deltas, D_scenarios_all = generate_scenarios(D_all, n_scenarios, shift_range=8.0, seed=42)  # Larger shifts for respiratory motion

    # Build constraint matrices
    D_min = 0.95 * target_dose

    A_rows = []
    b_values = []

    # Target coverage (minimum dose): -D @ x + D_min <= 0 means D @ x >= D_min
    A_rows.extend(-D_target)
    b_values.extend([D_min] * D_target.shape[0])  # Positive b for target min

    # OAR limits (maximum dose): D @ x - D_max <= 0 means D @ x <= D_max
    for name, D_oar in D_oars.items():
        A_rows.extend(D_oar)
        b_values.extend([-oar_limits.get(name, 30.0)] * D_oar.shape[0])  # Negative b for OAR max

    A_nominal = np.array(A_rows)
    b_nominal = np.array(b_values)

    # Generate scenario A matrices
    n_t = D_target.shape[0]
    A_scenarios = []
    for k in range(n_scenarios):
        D_k = D_scenarios_all[k]
        D_target_k = D_k[:n_t]

        A_k_rows = list(-D_target_k)
        idx = n_t
        for name, D_oar in D_oars.items():
            n_oar = D_oar.shape[0]
            A_k_rows.extend(D_k[idx:idx+n_oar])
            idx += n_oar

        A_scenarios.append(np.array(A_k_rows))

    # Build affine strings
    print("Building affine constraint expressions...")
    A_d_strings, b_d_strings = build_affine_constraint_strings(
        A_nominal, deltas, A_scenarios, b_nominal  # b already has correct signs
    )

    # Estimate appropriate max_intensity from reference solution if available
    ref_solution = patient.get('solution', None)
    if ref_solution is not None and len(ref_solution) > 0:
        max_intensity = 1.5 * np.max(ref_solution)  # Allow 50% above max reference
    else:
        # Scale based on required dose vs typical dose coefficient
        typical_dose_coeff = np.mean(D_target)
        max_intensity = 2.0 * target_dose / (n_beamlets * typical_dose_coeff)
    max_intensity = max(max_intensity, 1000.0)  # At least 1000 for TROTS liver data
    print(f"Max intensity: {max_intensity:.1f}")

    # Create QP objective
    print("Building QP objective...")
    Q, c, G, h, _, _ = create_qp_problem(
        D_target, D_oars, target_dose=target_dose,
        oar_limits=oar_limits,
        weights={'target': 10.0, 'Liver': 2.0, 'Spinal_Cord': 3.0},
        max_intensity=max_intensity
    )

    # Save files
    print(f"\nSaving to {output_dir}...")

    pd.DataFrame(deltas).to_csv(output_dir / 'scenarios.csv', index=False, header=False)
    pd.DataFrame(A_d_strings).to_csv(output_dir / 'A_d.csv', index=False, header=False)
    pd.DataFrame(b_d_strings).to_csv(output_dir / 'b_d.csv', index=False, header=False)
    pd.DataFrame(Q).to_csv(output_dir / 'Q.csv', index=False, header=False)
    pd.DataFrame(c).to_csv(output_dir / 'c.csv', index=False, header=False)
    pd.DataFrame(G).to_csv(output_dir / 'G.csv', index=False, header=False)
    pd.DataFrame(h).to_csv(output_dir / 'h.csv', index=False, header=False)

    D_combined = np.vstack([D_target] + list(D_oars.values()))
    pd.DataFrame(D_combined).to_csv(output_dir / 'D_nominal.csv', index=False, header=False)

    with open(output_dir / 'anatomy.txt', 'w') as f:
        f.write(f"PTV: 0-{D_target.shape[0]-1} (target, {D_target.shape[0]} voxels)\n")
        idx = D_target.shape[0]
        for name, D_oar in D_oars.items():
            f.write(f"{name}: {idx}-{idx + D_oar.shape[0]-1} (OAR, {D_oar.shape[0]} voxels)\n")
            idx += D_oar.shape[0]

    with open(output_dir / 'parameters.txt', 'w') as f:
        f.write(f"n_beamlets: {D_target.shape[1]}\n")
        f.write(f"n_voxels: {D_combined.shape[0]}\n")
        f.write(f"n_scenarios: {n_scenarios}\n")
        f.write(f"target_dose: {target_dose}\n")
        f.write(f"D_min: {D_min}\n")
        for name, limit in oar_limits.items():
            f.write(f"{name}_max: {limit}\n")
        f.write(f"max_intensity: 100.0\n")

    print("Done!")
    return output_dir


